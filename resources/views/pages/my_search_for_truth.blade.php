            <h1 style="font-size: 2.5rem; text-align: center; margin-bottom: 1.5rem; color: #333;">My Search for Truth</h1>

            <p style="margin-bottom: 1.5rem; line-height: 1.6;">People sometimes ask why I write the books I write, and what gives me the right to write them.</p>
            <p style="margin-bottom: 1.5rem; line-height: 1.6;">I don't have a seminary degree or a research chair. What I have is a question that was forced on me in 1999, and more than two decades spent refusing to let it go.</p>

            <h2 style="font-size: 1.8rem; margin-top: 2rem; margin-bottom: 1rem; color: #333;">Where It Started</h2>
            <p style="margin-bottom: 1.5rem; line-height: 1.6;">In 1999 I became gravely ill and had a near-death experience. Until that moment I had assumed, without ever really examining it, that the material world was all there was: the body was a biological machine, and when it stopped, there was nobody left to notice.</p>
            <p style="margin-bottom: 1.5rem; line-height: 1.6;">Then my body disappeared, and the lights stayed on. I remained aware.</p>
            <p style="margin-bottom: 1.5rem; line-height: 1.6;">I did not come back with answers. I came back with a question I could no longer avoid: if I was still aware without a body, what exactly had I been calling "myself" all along, and what does that mean for how I live, what I fear and what I can trust?</p>
            <p style="margin-bottom: 1.5rem; line-height: 1.6;">That question did not go away. It became the organising force behind everything I have read, studied and eventually written since.</p>

            <h2 style="font-size: 1.8rem; margin-top: 2rem; margin-bottom: 1rem; color: #333;">Why I Didn't Stop at One Tradition</h2>
            <p style="margin-bottom: 1.5rem; line-height: 1.6;">The honest starting point was the Christian tradition I already knew. But the question was bigger than any single doctrine, so I kept going: into the contemplatives and mystics within Christianity, into the Bible scholarship and the Gnostic texts left out of it, into Vedanta and the yoga tradition, into Buddhism and the non-dual teachers, into the modern science of consciousness and near-death studies, into Hermeticism and the older esoteric schools.</p>
            <p style="margin-bottom: 1.5rem; line-height: 1.6;">I was not looking for a tradition to belong to. I was looking for where they agreed, where they genuinely disagreed, and whether any of it matched what I had directly experienced when I had no body left to argue with.</p>
            <p style="margin-bottom: 1.5rem; line-height: 1.6;">Between my Kindle and Audible libraries that search now runs to several hundred books. What follows isn't the whole shelf, it's a representative selection, grouped by subject, with the purely technical reading (software, business) left out as beside the point here.</p>

