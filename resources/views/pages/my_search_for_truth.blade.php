            <h2 style="font-size: 1.8rem; margin-top: 2rem; margin-bottom: 1rem; color: #333;">From Research to Writing</h2>
            <p style="margin-bottom: 1.5rem; line-height: 1.6;">None of my books started as a publishing plan. Each one started as me trying to settle something in my own mind, usually by writing it down until I could see whether it actually held together.</p>

            <div class="msft-map">
                <strong>Beyond Death: The Architecture of Immortality</strong>
                Grew directly out of the consciousness and near-death research above: what current physics, biology and first-hand testimony actually say about whether mortality is the fixed law we assume it is.
            </div>

            <div class="msft-map">
                <strong>Death-Bed Visions (annotated edition)</strong>
                Sir William Barrett's 1926 case studies sit at the root of the modern near-death literature. Annotating his original work was a way of tracing the evidence back to where it started.
            </div>

            <div class="msft-map">
                <strong>The Yoga Sūtras of Patañjali (new translation)</strong>
                Came directly from years inside the Vedanta and yoga reading above, especially Satchidananda's and Easwaran's translations, and from the Advanced Yoga Practices I have followed in my own meditation.
            </div>

            <div class="msft-map">
                <strong>Breath, Silence and Stillness in Action</strong>
                A practical distillation of the same yoga and meditation study: spinal breathing, deep meditation and samyama, tested in my own practice before I tried to teach it.
            </div>

            <div class="msft-map">
                <strong>The Biblical Process of Manifestation</strong>
                Sits where the Christian contemplative tradition and the New Thought material above meet: what the Bible actually says about prayer, faith and receiving, read against two very different interpretive lenses.
            </div>

            <div class="msft-map">
                <strong>Hidden Wisdom: Interpretations of the Gospel of Thomas</strong>
                Came from the early Christianity and Gnostic reading above, and the question of what got left out of the Bible as it was assembled, and why.
            </div>

            <div class="msft-map">
                <strong>Did the Prophets See This?</strong>
                Grew from the Bible study and prophecy reading, read alongside current geopolitics rather than in isolation from it.
            </div>

            <div class="msft-map">
                <strong>A Profound Teaching, This Isn't Living and The Divergence</strong>
                All draw on the non-duality and awakening material above: the recurring claim, across very different teachers, that most of what we take to be "ourselves" is a layer that can be seen through.
            </div>

            <hr style="margin: 2.5rem 0; border: 0; border-top: 1px solid #eee;">

            <h2 style="font-size: 1.8rem; margin-top: 2rem; margin-bottom: 1rem; color: #333;">On Authority</h2>
            <p style="margin-bottom: 1.5rem; line-height: 1.6;">I don't claim authority in the academic sense. I have no doctorate in theology or neuroscience, and I'm not a monk or an ordained minister of any tradition.</p>
            <p style="margin-bottom: 1.5rem; line-height: 1.6;">What I can claim is this: I had an experience I couldn't explain away, I refused to settle for the first explanation that was handed to me, and I have spent more than two decades reading the people who took the same question seriously, from physicists to mystics to monks, often deliberately choosing sources that disagreed with each other so I couldn't simply confirm what I already believed.</p>
            <p style="margin-bottom: 1.5rem; line-height: 1.6;">My books are not the conclusion of that search. They are progress reports, written as honestly as I could manage, on what held together once that reading met what I had actually experienced.</p>
            <p style="margin-bottom: 1.5rem; line-height: 1.6;">I'd encourage you to test everything in them the same way I did: not by taking my word for it, but by reading widely, sitting with the question in stillness, and seeing what remains when the noise settles.</p>
            <p style="margin-bottom: 1.5rem; line-height: 1.6;">You can see where that search has led so far on my <a href="/books">books page</a>.</p>

