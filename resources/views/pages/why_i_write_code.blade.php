                <h1 style="font-size: 2.5rem; text-align: center; margin-bottom: 1.5rem; color: #333;">Why I Write Code: The Work That Gave Me My Life Back</h1>

                <p style="margin-bottom: 1.5rem; line-height: 1.6;">People might assume I write software because technology has always been my career.</p>
                <p style="margin-bottom: 1.5rem; line-height: 1.6;">That is only part of the story.</p>
                <p style="margin-bottom: 1.5rem; line-height: 1.6;">Before I became a software developer, I designed and built recycling machinery and complete recycling plants for industry and local government. My work existed in the physical world of steel, hydraulics, conveyors, drawings, fabrication and heavy machinery.</p>
                <p style="margin-bottom: 1.5rem; line-height: 1.6;">My day usually began at six in the morning.</p>
                <p style="margin-bottom: 1.5rem; line-height: 1.6;">I would go into the factory and meet with the engineering fabricators to discuss new plans and drawings. We would work through how the latest machine was to be constructed, identify problems and make whatever changes were needed.</p>
                <p style="margin-bottom: 1.5rem; line-height: 1.6;">From there, I might attend meetings with local government representatives about upcoming recycling programs or discuss new industrial projects. Then I would return to my office and continue designing the improved machinery those projects required.</p>
                <p style="margin-bottom: 1.5rem; line-height: 1.6;">It was demanding but satisfying work. We were solving real problems and building machines that had to perform reliably in the real world.</p>

                <div style="margin: 2rem 0;">
                    <img src="{{ url('/images/why_i_write_code_baler.jpg') }}" style="width:100%; border-radius: 6px;" alt="A baler and hydraulic recycling machine on the factory floor">
                    <p style="text-align: center; font-style: italic; color: #777; margin-top: 0.5rem; font-size: 0.95rem;">The machines I designed and built had to perform reliably in the real world, every day, without exception.</p>
                </div>

                <p style="margin-bottom: 1.5rem; line-height: 1.6;">But I was working very long hours.</p>
                <p style="margin-bottom: 1.5rem; line-height: 1.6;">There was always another drawing to complete, another fabrication problem to solve, another meeting to attend or another machine to improve. Eventually, my health broke under the strain. In 1999, I became gravely ill and experienced a near-death experience.</p>
                <p style="margin-bottom: 1.5rem; line-height: 1.6;">Until that moment, I had believed that the material world was all there was.</p>
                <p style="margin-bottom: 1.5rem; line-height: 1.6;">The body was a biological machine. When it stopped working, the lights went out and the party was over. There was nothing more to investigate because there was nobody left to investigate it.</p>
                <p style="margin-bottom: 1.5rem; line-height: 1.6;">Then my body disappeared, but the lights stayed on.</p>
                <p style="margin-bottom: 1.5rem; line-height: 1.6;">I remained aware.</p>
                <p style="margin-bottom: 1.5rem; line-height: 1.6;">I did not return with a complete explanation of death, consciousness or reality. What I returned with was something more disruptive: the certainty that my previous understanding had been incomplete.</p>
                <p style="margin-bottom: 1.5rem; line-height: 1.6;">Everything changed.</p>

                <hr style="margin: 2.5rem 0; border: 0; border-top: 1px solid #eee;">

                <p style="margin-bottom: 1.5rem; line-height: 1.6;">Before the experience, my attention had been directed almost entirely outward. I designed machines, solved mechanical problems and worked to change the physical world around me.</p>
                <p style="margin-bottom: 1.5rem; line-height: 1.6;">After the experience, that direction inverted.</p>
                <p style="margin-bottom: 1.5rem; line-height: 1.6;">I needed to understand where I had gone, what had remained aware and how awareness could continue when I no longer experienced having a body.</p>
                <p style="margin-bottom: 1.5rem; line-height: 1.6;">But serious investigation requires time, and the life I had been living consumed nearly all of it.</p>
                <p style="margin-bottom: 1.5rem; line-height: 1.6;">That was when software became important.</p>
                <p style="margin-bottom: 1.5rem; line-height: 1.6;">Moving from building and programming physical machines to writing software allowed me to continue doing what I naturally enjoyed: understanding systems, solving problems and creating things that worked.</p>
                <p style="margin-bottom: 1.5rem; line-height: 1.6;">But software changed the scale and structure of my working life.</p>
                <p style="margin-bottom: 1.5rem; line-height: 1.6;">I no longer needed a factory, a fabrication team or a large physical project around me before I could create something useful. With a computer, I could build complex systems in focused periods of work. In time, I could accomplish in a few concentrated hours what had once consumed an entire day.</p>
                <p style="margin-bottom: 1.5rem; line-height: 1.6;">Writing code gave me something more valuable than a new occupation.</p>
                <p style="margin-bottom: 1.5rem; line-height: 1.6;">It gave me time.</p>

                <hr style="margin: 2.5rem 0; border: 0; border-top: 1px solid #eee;">

                <p style="margin-bottom: 1.5rem; line-height: 1.6;">I used that time to investigate spiritual traditions, ancient texts, meditation, consciousness and the nature of identity. I was no longer satisfied with beliefs accepted from other people. I wanted to examine the pathways for myself and compare them with what I had directly experienced.</p>
                <p style="margin-bottom: 1.5rem; line-height: 1.6;">That investigation continued for years.</p>
                <p style="margin-bottom: 1.5rem; line-height: 1.6;">Eventually, the research began turning into books. Writing was not originally a publishing ambition. It was how I organised what I was discovering and tested whether I could express it clearly.</p>
                <p style="margin-bottom: 1.5rem; line-height: 1.6;">In hindsight, writing software and writing books are not as different as they first appear.</p>
                <p style="margin-bottom: 1.5rem; line-height: 1.6;">Both begin with something invisible.</p>
                <p style="margin-bottom: 1.5rem; line-height: 1.6;">A software system begins as an idea. You examine its underlying structure, identify the relationships between its parts, and gradually give it a form that other people can use.</p>
                <p style="margin-bottom: 1.5rem; line-height: 1.6;">A book begins in much the same way.</p>
                <p style="margin-bottom: 1.5rem; line-height: 1.6;">The difference is that software helps me investigate and organise the systems we build, while my books investigate the system in which we find ourselves: consciousness, identity, life, death and the reality beneath our everyday assumptions.</p>

                <hr style="margin: 2.5rem 0; border: 0; border-top: 1px solid #eee;">

                <p style="margin-bottom: 1.5rem; line-height: 1.6;">I still write code because I enjoy building useful systems and solving difficult problems. But code also gave me the freedom to pursue the question that changed my life:</p>
                <p style="text-align: center; font-style: italic; color: #555; margin-bottom: 1.5rem;">What was it that remained aware when my body was no longer there?</p>
                <p style="margin-bottom: 1.5rem; line-height: 1.6;">I once designed machines that processed the material world. Today, I write software that gives me the time and freedom to investigate what may exist beyond it.</p>
                <p style="margin-bottom: 1.5rem; line-height: 1.6;">Code did not become the purpose of my life.</p>
                <p style="margin-bottom: 1.5rem; line-height: 1.6;">It became the structure that allowed me to pursue it.</p>
                <p style="margin-bottom: 1.5rem; line-height: 1.6;">My books and continuing investigation can be found at <a href="https://mauriceprice.net/">MauricePrice.net</a>.</p>
